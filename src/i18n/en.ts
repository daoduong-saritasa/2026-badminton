function ordinal(position: number): string {
  const suffix = position % 10 === 1 && position % 100 !== 11 ? 'st'
    : position % 10 === 2 && position % 100 !== 12 ? 'nd'
      : position % 10 === 3 && position % 100 !== 13 ? 'rd'
        : 'th'
  return `${formatNumber(position)}${suffix}`
}
